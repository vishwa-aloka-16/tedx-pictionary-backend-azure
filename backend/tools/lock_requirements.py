"""Lock only the installed application dependency tree, never pip-freeze the whole venv."""
from collections import deque
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

BACKEND = Path(__file__).resolve().parents[1]


def main():
    roots = [Requirement(line) for raw in (BACKEND / 'requirements.in').read_text().splitlines()
             if (line := raw.split('#', 1)[0].strip())]
    direct = {canonicalize_name(req.name): req for req in roots}
    queue = deque(roots)
    processed = set()
    versions = {}
    while queue:
        req = queue.popleft()
        key = (canonicalize_name(req.name), frozenset(req.extras))
        if key in processed:
            continue
        processed.add(key)
        dist = metadata.distribution(req.name)
        versions[key[0]] = dist.version
        for item in dist.requires or []:
            dependency = Requirement(item)
            if dependency.marker is None or any(dependency.marker.evaluate({'extra': extra})
                                                for extra in {'', *req.extras}):
                queue.append(dependency)
    lines = [
        '# Generated by backend/tools/lock_requirements.py; do not loosen individual pins.',
        '# Baseline: CPython 3.14; preserves the tested TensorFlow RC / Keras nightly.',
        '# Windows dependencies are conditional; uvloop is explicitly pinned for Linux.',
        '# See backend/DEPLOYMENT.md before updating the model runtime.',
        '',
    ]
    for name, version in sorted(versions.items()):
        extras = sorted(direct[name].extras) if name in direct else []
        requirement = name + ('[' + ','.join(extras) + ']' if extras else '') + '==' + version
        if name == 'colorama':
            requirement += '; sys_platform == "win32"'
        # An existing Linux installation is normalized to the cross-platform pin below.
        if name != 'uvloop':
            lines.append(requirement)
    lines.append('uvloop==0.23.0; sys_platform != "win32" and sys_platform != "cygwin" and platform_python_implementation != "PyPy"')
    (BACKEND / 'requirements.txt').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Wrote backend/requirements.txt with exact direct and transitive runtime pins.')


if __name__ == '__main__':
    main()
